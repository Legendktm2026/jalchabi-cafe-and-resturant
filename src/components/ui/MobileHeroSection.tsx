import React, { useEffect, useState } from 'react';
import { ArrowDown, Sparkles } from 'lucide-react';
import { useLanguage } from '../../context/LanguageContext';

interface MobileHeroSectionProps {
  onOrderClick: () => void;
  onNavigateSection: (id: string) => void;
  onEnable3D: () => void;
}

/**
 * Phase 1 — Mobile-First Hero Section
 *
 * Replaces the heavy Three.js WebGL canvas on non-flagship phones.
 * Loads in <1.5s (static image + CSS only), no JavaScript animation libraries.
 * Preserves an escape hatch ("✨ 3D Art Edition") for users who want the full experience.
 *
 * Desktop / Tablet (≥768px): This component is never rendered — see App.tsx.
 */
export const MobileHeroSection: React.FC<MobileHeroSectionProps> = ({
  onOrderClick,
  onNavigateSection,
  onEnable3D,
}) => {
  const { language } = useLanguage();
  const [visible, setVisible] = useState(false);

  // Trigger CSS entrance animation on mount (avoids flash of invisible content)
  useEffect(() => {
    const t = requestAnimationFrame(() => setVisible(true));
    return () => cancelAnimationFrame(t);
  }, []);

  return (
    <section
      id="experience"
      className="relative w-full h-[100svh] min-h-[580px] flex flex-col justify-end overflow-hidden bg-[#070e0c]"
    >
      {/* ── Background image ──────────────────────────────────────────────────
          Preloaded via <link rel="preload"> in index.html (Phase 8).
          <picture> provides WebP with JPG fallback for broad browser support.
      ─────────────────────────────────────────────────────────────────────── */}
      <div className="absolute inset-0 z-0">
        <picture>
          {/* WebP generated by scripts/convert-hero-webp.cjs (Phase 8) */}
          <source srcSet="/images/jalchabi-exterior-dusk.webp" type="image/webp" />
          <img
            src="/images/jalchabi-exterior-dusk.jpg"
            alt="Jalchabi Cafe & Restaurant exterior — Sarberia, Canning II at dusk"
            className="w-full h-full object-cover object-center"
            fetchPriority="high"
            decoding="async"
          />
        </picture>
        {/* Cinematic dark gradient: dark top (navbar readable) → lighter middle (image visible) → very dark bottom (text readable) */}
        <div className="absolute inset-0 bg-gradient-to-b from-[#070e0c]/75 via-[#070e0c]/35 to-[#070e0c]/95" />
      </div>

      {/* ── Content layer ─────────────────────────────────────────────────── */}
      <div
        style={{ paddingBottom: 'calc(9rem + env(safe-area-inset-bottom, 0px))' }}
        className={`relative z-10 flex flex-col justify-end w-full px-5 transition-all duration-700 ease-out ${
          visible ? 'opacity-100 translate-y-0' : 'opacity-0 translate-y-4'
        }`}
      >
        {/* Top row: Live location badge & 3D Art Edition escape hatch */}
        <div className="flex items-center justify-between mb-3 w-full">
          <a
            href="https://share.google/YxnV3K2qeoJCWx2Ua"
            target="_blank"
            rel="noopener noreferrer"
            title="Open Jalchabi on Google Maps"
            className="flex items-center gap-2 hover:opacity-80 transition-opacity cursor-pointer"
          >
            <span className="w-2 h-2 rounded-full bg-[#dfb86c] animate-pulse shrink-0" />
            <span className="text-[10px] font-mono uppercase tracking-[0.2em] text-[#e6ece9]">
              {language === 'bn' ? 'সারবেড়িয়া, ক্যানিং ২ ↗' : 'Sarberia, Canning II ↗'}
            </span>
          </a>

          <button
            type="button"
            onClick={onEnable3D}
            className="flex items-center gap-1.5 px-3 py-1 rounded-full border border-[#dfb86c]/40 text-[10px] font-mono uppercase tracking-wider text-[#dfb86c] bg-[#0e1b17]/85 backdrop-blur-sm active:scale-95 transition-all shadow-sm"
          >
            <Sparkles className="w-3 h-3 text-[#dfb86c]" />
            <span>3D Art Edition</span>
          </button>
        </div>

        {/* Main headline */}
        <h1 className="font-serif text-3xl sm:text-4xl font-light text-[#fdfbf7] leading-[1.15] tracking-wide mb-2">
          {language === 'bn' ? (
            <>
              ক্যানিং ২–এর<br />
              <span className="text-[#e5c378]">সেরা রেস্তোরাঁ</span>
            </>
          ) : (
            <>
              Canning II's Most<br />
              <span className="text-[#e5c378]">Beautiful Dining</span>
            </>
          )}
        </h1>

        {/* Subtitle */}
        <p className="text-xs sm:text-sm text-[#8fa69d] mb-4 leading-relaxed max-w-xs">
          {language === 'bn'
            ? 'দার্জিলিং মোমো, ড্রামস অফ হেভেন, শাহি বিরিয়ানি — সরাসরি অর্ডার করুন'
            : 'Darjeeling Momos, Drums of Heaven, Royal Biryani — order directly'}
        </p>

        {/* ── Primary CTA — Golden pulse button ─────────────────────────── */}
        <button
          type="button"
          onClick={onOrderClick}
          className="w-full py-3.5 rounded-2xl bg-gradient-to-r from-[#dfb86c] via-[#ebd08d] to-[#c99e52] text-[#070e0c] font-bold text-sm sm:text-base tracking-wide animate-pulse-slow active:scale-[0.98] transition-transform mb-2 select-none shadow-lg shadow-[#dfb86c]/25"
        >
          {language === 'bn' ? '🍛 মেনু দেখুন ও অর্ডার করুন' : '🍛 See Menu & Order Now'}
        </button>

        {/* Scroll-down explore hint */}
        <div className="flex justify-center">
          <button
            type="button"
            onClick={() => onNavigateSection('story')}
            className="flex items-center gap-1.5 text-[#8fa69d] text-xs active:text-[#fdfbf7] transition-colors py-1"
          >
            <ArrowDown className="w-3.5 h-3.5 text-[#dfb86c]" />
            <span>{language === 'bn' ? 'আরও জানুন' : 'Explore'}</span>
          </button>
        </div>
      </div>
    </section>
  );
};
